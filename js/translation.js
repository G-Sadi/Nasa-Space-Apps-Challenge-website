// গ্লোবাল ফাংশন: ভাষা পরিবর্তন করা
function setLanguage(lang) {
    const elements = document.querySelectorAll("[data-i18n]");
    
    elements.forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (!key) return;
        const lookupKey = (translations[lang] && translations[lang][key] !== undefined)
            ? key
            : key.replace(/-/g, "_");
        if (translations[lang] && translations[lang][lookupKey] !== undefined) {
            el.textContent = translations[lang][lookupKey];
        }
    });

    const toggle = document.getElementById("langToggle");
    const enLabel = document.getElementById("langEnLabel");
    const bnLabel = document.getElementById("langBnLabel");

    if (lang === "bn") {
        document.body.classList.add("lang-bn");
        if (toggle) toggle.checked = true;
        if (bnLabel) bnLabel.classList.add("active");
        if (enLabel) enLabel.classList.remove("active");
        document.documentElement.lang = "bn";
    } else {
        document.body.classList.remove("lang-bn");
        if (toggle) toggle.checked = false;
        if (enLabel) enLabel.classList.add("active");
        if (bnLabel) bnLabel.classList.remove("active");
        document.documentElement.lang = "en";
    }

    localStorage.setItem("preferred_lang", lang);

    // Broadcast languageChanged custom event so components (like FarmerBuddy & 3D Simulation) sync
    try {
        window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
    } catch (e) {
        console.warn("[translation] Could not dispatch languageChanged event:", e);
    }
}

// পেজ লোড হলে সংরক্ষিত ভাষা লোড করা ও ইভেন্ট লিসেনার সেট করা
document.addEventListener("DOMContentLoaded", () => {
    const toggle = document.getElementById("langToggle");
    
    // ব্রাউজারে সেভ থাকলে সেটি নেবে, ডিফল্ট ইংরেজি ('en')
    const savedLang = localStorage.getItem("preferred_lang") || "en";
    setLanguage(savedLang);

    if (toggle) {
        toggle.addEventListener("change", (e) => {
            const chosenLang = e.target.checked ? "bn" : "en";
            setLanguage(chosenLang);
        });
    }
});